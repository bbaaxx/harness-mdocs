#!/usr/bin/env node
// Generates src/core/build-info.ts with the current git SHA and package version (or nulls).
const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const outPath = path.join(repoRoot, 'src', 'core', 'build-info.ts');

let sha = null;
try {
  sha = execSync('git rev-parse --short HEAD', { cwd: repoRoot, stdio: ['ignore', 'pipe', 'ignore'] })
    .toString()
    .trim();
} catch {
  sha = null;
}

let version = null;
try {
  const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf8'));
  version = typeof pkg.version === 'string' ? pkg.version : null;
} catch {
  version = null;
}

const content =
  '// GENERATED by scripts/write-build-info.js — do not edit\n' +
  `export const BUILD_GIT_SHA: string | null = ${sha === null ? 'null' : `"${sha}"`};\n` +
  `export const BUILD_VERSION: string | null = ${version === null ? 'null' : `"${version}"`};\n`;

fs.writeFileSync(outPath, content);
console.log(
  `build-info.ts written (BUILD_GIT_SHA=${sha === null ? 'null' : sha}, BUILD_VERSION=${version === null ? 'null' : version})`
);
